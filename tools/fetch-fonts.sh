#!/usr/bin/env bash
# tools/fetch-fonts.sh — self-host the three families used by this site.
#
# Why: no Node means no fontsource/npm pipeline, and a Google Fonts <link> would
# be a third-party render-blocking request. This pulls the woff2 files once,
# keeps only the latin + latin-ext subsets, and writes assets/css/fonts.css with
# local urls. Re-run only when the font list below changes.
#
# All three families are SIL Open Font License 1.1.

set -euo pipefail

cd "$(dirname "$0")/.."

CSS_URL='https://fonts.googleapis.com/css2?family=Fraunces:opsz,wght,SOFT,WONK@9..144,300..700,0..100,0..1&family=Manrope:wght@400..700&family=IBM+Plex+Mono:wght@400;500&display=swap'
# A modern-browser UA is required or Google serves legacy ttf instead of woff2.
UA='Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/122.0.0.0 Safari/537.36'

OUT_CSS='assets/css/fonts.css'
OUT_DIR='assets/fonts'

mkdir -p "$OUT_DIR" assets/css

tmp="$(mktemp)"
trap 'rm -f "$tmp"' EXIT
curl -fsS -A "$UA" "$CSS_URL" -o "$tmp"

{
  printf '/* GENERATED by tools/fetch-fonts.sh — do not edit by hand.\n'
  printf ' * Fraunces (variable: opsz, wght, SOFT, WONK)\n'
  printf ' * Manrope (variable: wght) · IBM Plex Mono (400, 500)\n'
  printf ' * latin + latin-ext subsets only. SIL Open Font License 1.1.\n'
  printf ' * Local files live in assets/fonts/; paths below are relative to assets/css/. */\n\n'
} > "$OUT_CSS"

subset=''
block=''
in_block=0
count=0

while IFS= read -r line || [ -n "$line" ]; do
  case "$line" in
    '/* '*)
      subset="$(printf '%s' "$line" | sed -e 's|^/\* ||' -e 's| \*/$||')"
      ;;
    '@font-face {'*)
      in_block=1
      block="$line"$'\n'
      continue
      ;;
  esac

  if [ "$in_block" = 1 ]; then
    block="$block$line"$'\n'
    case "$line" in
      '}'*)
        in_block=0
        if [ "$subset" = 'latin' ] || [ "$subset" = 'latin-ext' ]; then
          url="$(printf '%s' "$block" | grep -o 'https://fonts\.gstatic\.com[^)]*\.woff2' | head -1)"
          fam="$(printf '%s' "$block" | grep -o "font-family: '[^']*'" | head -1 | sed -e "s|font-family: '||" -e "s|'||")"
          wght="$(printf '%s' "$block" | grep -o 'font-weight: [^;]*' | head -1 | sed -e 's|font-weight: ||' | tr ' ' '-')"
          slug="$(printf '%s' "$fam" | tr 'A-Z' 'a-z' | tr ' ' '-')"
          name="${slug}-${wght}-${subset}.woff2"
          curl -fsS -A "$UA" "$url" -o "$OUT_DIR/$name"
          printf '%s' "$block" | sed -e "s|$url|../fonts/$name|" >> "$OUT_CSS"
          printf '\n' >> "$OUT_CSS"
          count=$((count + 1))
          printf '  %s\n' "$name"
        fi
        ;;
    esac
  fi
done < "$tmp"

printf 'fetch-fonts.sh: wrote %s @font-face rules to %s\n' "$count" "$OUT_CSS"
